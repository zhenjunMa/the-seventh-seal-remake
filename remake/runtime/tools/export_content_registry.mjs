// Compile one editable registration after checking source-backed runtime dependencies.
import {readFile,writeFile,rename,access} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {validateContentDependencies} from '../web/core/content_dependencies.mjs';
import {validateForestStage} from '../web/forest_stage.mjs';
import {readContentDefinition} from './resolve_content_definition.mjs';
import {requireContentReadiness} from '../web/core/content_readiness.mjs';
const web=fileURLToPath(new URL('../web/',import.meta.url)),prototype=fileURLToPath(new URL('../../prototype/web/',import.meta.url)),original=fileURLToPath(new URL('../../../',import.meta.url));
const digest=bytes=>createHash('sha256').update(bytes).digest('hex');
const inputs={};
const local=value=>value.startsWith('/prototype/')?path.join(prototype,value.slice(11)):path.join(web,value.replace(/^\//,''));
async function read(name){const raw=await readFile(local(name));inputs[name]=digest(raw);return JSON.parse(raw);}
export async function auditContentFiles(){
  const {definition,content,input_sha256}=await readContentDefinition();Object.assign(inputs,input_sha256);
  const names={catalog:'catalog',seed:'opening_seed',story:'chapter_story',resources:'chapter_map_resources',party:'party_combat',commands:'party_skills',forest:'forest_combat',ai:'forest_ai',rewards:'party_rewards',reactions:'party_reactions',status:'forest_status',encounters:'encounters',view:'party_battle_view',itemView:'item_presentation',lifecycle:'battle_lifecycle',menu:'operation_menu'};
  const data=Object.fromEntries(await Promise.all(Object.entries(names).map(async([key,name])=>[key,await read(`data/${name}.json`)])));
  const counts=validateContentDependencies(content,data),checked=new Set();
  const readiness=requireContentReadiness(content,data.story,data.resources);
  for(const source of [...Object.values(content.roles).map(role=>role.source),...Object.values(content.programs)]){
    const raw=await readFile(path.join(original,source.path));
    if(digest(raw)!==source.sha256)throw new Error(`原输入与内容登记不同：${source.path}`);
    inputs[`original/${source.path}`]=source.sha256;
  }
  async function references(value){
    if(Array.isArray(value)){for(const child of value)await references(child);return;}
    if(value&&typeof value==='object'){for(const child of Object.values(value))await references(child);return;}
    if(typeof value!=='string'||!/^\/?(?:prototype\/)?(?:assets|data)\/[A-Za-z0-9_./-]+\.(?:png|mp3|wav|mp4|json)$/.test(value))return;
    if(value.split('/').some(part=>part==='.'||part==='..'))throw new Error(`内容路径越界：${value}`);
    const file=local(value);if(checked.has(file))return;checked.add(file);await access(file);
    if(file.endsWith('.json'))await references(await read(value));
  }
  for(const row of Object.values(data))await references(row);
  for(const [id,row]of Object.entries(content.maps)){
    const map=await read(row.path);if(map.id!==id)throw new Error(`地图身份不一致：${id}`);await references(map);
  }
  for(const [id,row]of Object.entries(content.stages)){
    const stage=await read(row.path);if(stage.stage_id!==id)throw new Error(`场景身份不一致：${id}`);
    validateForestStage(stage,content);await references(stage);
  }
  return {definition,content,report:{schema:'seventh-seal-content-dependencies',version:1,passed:true,...counts,readiness,resource_files_checked:checked.size,input_sha256:inputs}};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const {definition,content,report}=await auditContentFiles();
  const output=path.join(web,'data/runtime_content.mjs'),text='// Generated by tools/export_content_registry.mjs; edit runtime_content.json.\nexport const definition = '+JSON.stringify(definition,null,2)+';\nexport default '+JSON.stringify(content,null,2)+';\n';
  const current=await readFile(output,'utf8').catch(error=>{if(error.code!=='ENOENT')throw error;return ''});
  if(process.argv.includes('--check')&&current!==text)throw new Error('内容登记未编译，请运行 build_runtime.py --target content --run');
  if(!process.argv.includes('--check')&&current!==text){await writeFile(output+'.tmp',text);await rename(output+'.tmp',output);}
  await writeFile(new URL('../evidence/content_dependencies.json',import.meta.url),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify({passed:true,roles:report.roles,maps:report.maps,programs:report.programs,resource_files_checked:report.resource_files_checked,check_only:process.argv.includes('--check')}));
}
